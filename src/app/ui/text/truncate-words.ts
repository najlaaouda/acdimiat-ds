/* ============================================================================
   Acadimiat UI — الاقتطاع بالكلمات
   ----------------------------------------------------------------------------
   مصدر واحد لقاعدة القصّ، يستهلكه مستهلكان:

     • `<ap-media-cell>` عبر `[maxWords]` — حين تكون الخليّة أفاتارًا وعنوانًا
       وسطرًا ثانويًا، وهي النمط الغالب في عمود «الاسم».
     • `apTruncateWords` (أنبوب) — حين لا تصلح خليّة الوسائط: أشهر حالاتها
       اسمٌ **قابل للنقر**، إذ عنوان خليّة الوسائط `<span>` لا `<a>`.

   ⚠️ ولا تُنسخ هذه الدالّة إلى أيّ منهما: نسختان من قاعدة واحدة تتباعدان
      أوّل مرّة يُعدَّل أحدهما — وهي القاعدة نفسها التي تحكم `ui/select/_menu`
      بين القائمتين المرسومتين.

   ─── ما الذي يُقتطع، وما الذي لا يُقتطع ────────────────────────────────────
       يُقتطع ما يبقى معرِّفًا بعد الاقتطاع   ← الاسم
       لا يُقتطع ما يصير بالاقتطاع خطأً       ← البريد، الهاتف، المعرّف

   «محمد عبدالرحمن الدوسري…» يبقى اسمًا يُعرف صاحبه. أمّا «mohammed.abd…»
   فليس بريدًا ناقصًا بل بريدٌ **خاطئ**: من ينسخه يرسل إلى عنوان لا وجود له،
   ومن يقارنه بعنوان في يده يخطئ المطابقة. وأربع خانات محذوفة من رقم هاتف
   لا تُخمَّن.

   ─── وبالكلمات لا بالمحارف ─────────────────────────────────────────────────
   القصّ عند محرف بعينه يقع في وسط كلمة فيُنتج «محمد عبدالرح…» — يُقرأ خطأً
   مطبعيًّا لا اختصارًا. والقصّ عند حدّ الكلمة يُبقي كلّ ما يظهر **صحيحًا**،
   وينقص عدد الكلمات وحده.

   ⚠️ ولا `slice` على المحارف أصلًا: الحرف قد يكون زوجًا من وحدات UTF-16،
      وقصّ السلسلة يشطره فيظهر محرف تالف. التقسيم على المسافات لا يمرّ بهذا
      الاحتمال.
   ============================================================================ */

/** المحرف الواحد ‎…‎ لا ثلاث نقاط: نقطة واحدة في الخطّ، وقارئ الشاشة يعرفها. */
const ELLIPSIS = '…';

/**
 * يُرجع النصّ مقصوصًا عند `maxWords` كلمة، أو كما هو.
 *
 * `maxWords` صفرًا أو أقلّ يُعطّل القصّ — وهو الافتراضي في `<ap-media-cell>`.
 *
 * ⚠️ ولا تُضاف النقاط إلّا إذا كانت هناك كلمة **زائدة** فعلًا: اسم من ثلاث
 *    كلمات مع حدّ ثلاث كلمات يبقى بلا نقاط، فالنقاط بعد نصّ كامل تَعِد
 *    بمزيد لا وجود له.
 */
export function truncateWords(value: string | null | undefined, maxWords: number): string {
  const text = (value ?? '').trim();
  if (!text || !(maxWords > 0)) {
    return text;
  }

  /* التقسيم على أي متتالية مسافات: الأسماء المنسوخة من مصادر أخرى تحمل
     مسافات مزدوجة وأخرى غير قابلة للكسر، وعدّها كلماتٍ يقتطع باكرًا. */
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length <= maxWords) {
    return text;
  }

  return words.slice(0, maxWords).join(' ') + ELLIPSIS;
}
