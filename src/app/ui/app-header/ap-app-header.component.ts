import {
  ChangeDetectionStrategy,
  Component,
  Input,
  computed,
  ViewEncapsulation,
  signal,
} from '@angular/core';

/* ============================================================================
   Acadimiat UI — الشريط العلوي لهيكل اللوحة
   ----------------------------------------------------------------------------
   هوية الأكاديمية في جهة البداية، وأفعالها وأدواتها وحسابها في الطرف المقابل.

   ─── ما يميّزه عن <ap-page-header> ────────────────────────────────────────
   الاثنان «رأس»، والفرق بينهما هو النطاق لا الموضع:

     <ap-app-header>   ثابت عبر الشاشات كلّها. لا يعرف أي صفحة مفتوحة تحته،
                       ولا يجوز أن يعرف. ما فيه يخصّ **الأكاديمية**: اسمها،
                       رابط موقعها، إشعاراتها، حساب من يديرها.
     <ap-page-header>  يتبدّل مع كل شاشة، ويعيش **داخل** البطاقة. ما فيه
                       يخصّ الصفحة: عنوانها، وصفها، وفعلها الرئيسي.

   والسؤال الذي يحسم موضع أي فعل جديد: هل يبقى صحيحًا لو انتقل المستخدم إلى
   شاشة أخرى؟ إن كان الجواب لا، فمكانه داخل البطاقة لا هنا. وهذا امتداد
   للقاعدة نفسها التي أنزلت «تصدير كملف إكسل» من رأس صفحة المستخدمين إلى
   شريط أدوات كل تبويب: نطاق الفعل يتبع موضعه.

   ─── لماذا <header> حقيقي والمضيف display: contents ────────────────────────
   `banner` معلَم مجّاني مع الوسم الأصلي، ولا يحتاج دورًا يُكتب ويُنسى — وهو
   السبب نفسه الموثّق في <ap-tab-nav> لاختيار <nav> على div بدور.

   والمضيف `display: contents` كي يبقى <header> نفسه في تدفّق حاويه: اللصق
   (`position: sticky`) يُحسب مقابل أقرب حاوٍ يمرَّر، وطبقةٌ إضافية بينهما
   تكسره بصمت.

   ─── ثلاثة منافذ، وكلّ منها فجوة مختلفة ────────────────────────────────────
   الفصل بينها ليس تنظيمًا: لكلٍّ قاعدة تباعد لا تصحّ على الآخر.

     [apAppHeaderBrand]    الشعار — صورة يملكها المستهلك، يُحدّ ارتفاعها فقط.
     [apAppHeaderActions]  أزرار تحمل كلمات — فجوة 12px تفصل النصّين.
     [apAppHeaderTools]    أيقونات عارية وزنّاد الحساب — فجوة 4px، فهي صفّ
                           واحد من الأدوات لا ثلاثة أزرار متفرّقة.

   ─── ما لا يملكه المكوّن عمدًا ──────────────────────────────────────────────
   لا يعرف الشعار ولا الإشعارات ولا قائمة الحساب. كلّها محتوى مُسقَط: أوّلها
   أصل ثابت للعلامة، والثانية تحتاج عدّادًا حيًّا، والثالثة قائمة كاملة. ولو
   ابتلعها المكوّن لصار الشريطُ العلوي مكانَ ربط الخدمات، وهو أبعد ما يكون
   عن مكوّن نظام تصميم.

   ⚠️ القالب والأنماط في ملفين خارجيين — أي backtick داخل قالب سطري (ولو في
      تعليق) يُغلق النصّ الحرفي. لُدغ المشروع بذلك مرّتين.
   ============================================================================ */

@Component({
  selector: 'ap-app-header',
  standalone: true,
  changeDetection: ChangeDetectionStrategy.OnPush,
  encapsulation: ViewEncapsulation.None,
  templateUrl: './ap-app-header.component.html',
  styleUrl: './ap-app-header.component.scss',
})
export class ApAppHeaderComponent {
  private readonly academyName$ = signal('');
  private readonly academyUrl$ = signal('');
  private readonly label$ = signal('الشريط العلوي');
  private readonly sticky$ = signal(true);

  /**
   * اسم الأكاديمية المفتوحة — سياق لا عنوان.
   *
   * هو الجواب على «أي أكاديمية أدير الآن؟» لدى من يملك أكثر من واحدة، وهو
   * السؤال الوحيد الذي لا تجيب عنه أي شاشة تحته.
   *
   * ⚠️ نصّ مُدخَل لا محتوى مُسقَط — على خلاف الشعار بجانبه. الفرق أن الشعار
   *    عنصر (صورة أو رابط حولها) بينما هذا سلسلة نصّية واحدة يملك المكوّن
   *    لونها وحجمها وقصّها عند الضيق. وإسقاطه كان سيترك تنسيقه لكل مستهلك.
   *
   * ويُقصّ عند الضيق ولا يلتفّ: الشريط بارتفاع ثابت، فسطر ثانٍ يفيض منه.
   * والاسم الكامل يبقى في `title` لمن يحوم.
   */
  @Input()
  set academyName(value: string) {
    this.academyName$.set(value ?? '');
  }

  /**
   * رابط موقع الأكاديمية العامّ — يظهر أيقونةً ملاصقة للاسم حين يُمرَّر.
   *
   * كان زرًّا من ثلاث كلمات («زيارة موقع أكاديميتي») في الطرف المقابل من
   * الشريط. والموقع هو موقع **ذلك الاسم**، فالمسافة بينهما هي ما كانت تخفي
   * العلاقة — وحين لاصقه صار الرسم وحده كافيًا، وسقط عرضٌ دائم كان محجوزًا
   * لفعلٍ يقع مرّة في الجلسة.
   *
   * ⚠️ فارغًا لا تُرسَم الأيقونة أصلًا. رابطٌ بلا وجهة (`href=""`) يُعيد
   *    تحميل اللوحة نفسها، وهو أسوأ من غيابه.
   *
   * ونصّ الفقاعة ثابت في المكوّن لا مُدخَل: «زيارة موقع الأكاديمية» يصحّ في
   * كل أكاديمية، ومُدخَلٌ نصّي هنا يفتح بابًا لصياغة ثانية لنفس الشيء.
   */
  @Input()
  set academyUrl(value: string) {
    this.academyUrl$.set(value ?? '');
  }

  /** اسمُ الرابط لقارئ الشاشة، وهو نفسه نصّ الفقاعة — مصدر واحد لا اثنان. */
  protected readonly siteLinkLabel = 'زيارة موقع الأكاديمية';

  /**
   * اسم الرابط لقارئ الشاشة: الفعل + الوجهة.
   *
   * نصّ الرابط هو اسم الأكاديمية وحده، فلا يقول أنه يغادر اللوحة — وسلسلةٌ
   * ثابتة بلا اسم تجعل كل أكاديمية تُنطق بالجملة نفسها. فالاثنان معًا.
   */
  protected readonly siteLinkAriaLabel = computed(() => {
    const name = this.academyName$();
    return name ? `زيارة موقع «${name}»` : this.siteLinkLabel;
  });

  /**
   * اسم المعلَم لقارئ الشاشة.
   *
   * ⚠️ له قيمة افتراضية على خلاف `label` في <ap-tab-nav> التي تُرمى بدونها:
   *    الصفحة تحمل معلَم `banner` واحدًا لا غير، فلا لبس يُفرَّق به بين
   *    اثنين — بينما شرائط التبويب تتعدّد في الشاشة الواحدة.
   */
  @Input()
  set label(value: string) {
    this.label$.set(value || 'الشريط العلوي');
  }

  /**
   * اللصق أعلى الشاشة. مفعَّل افتراضيًا.
   *
   * شريطٌ علوي يمرّ مع الصفحة ويختفي هو مكوّن آخر: الإشعارات وزرّ زيارة
   * الموقع وقائمة الحساب أفعالٌ تُطلب من أي موضع في الصفحة، والوصول إليها
   * بالعودة إلى الأعلى في جدول من مئة صفّ كلفةٌ بلا مقابل.
   *
   * ويُطفأ حين يعيش الشريط داخل حاوٍ يمرَّر بنفسه — مسرح المعاينة في موقع
   * التوثيق مثلًا — إذ يلتصق حينها بحافّة المسرح لا بحافّة الشاشة.
   */
  @Input()
  set sticky(value: boolean) {
    this.sticky$.set(value !== false);
  }

  protected readonly academyNameValue = this.academyName$.asReadonly();
  protected readonly academyUrlValue = this.academyUrl$.asReadonly();
  protected readonly labelValue = this.label$.asReadonly();
  protected readonly stickyValue = this.sticky$.asReadonly();
}
