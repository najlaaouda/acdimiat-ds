import { InjectionToken } from '@angular/core';
import type { CountryCode } from 'libphonenumber-js';

/* ============================================================================
   Acadimiat UI — كاشف دولة المستخدم
   ----------------------------------------------------------------------------
   المكوّن **لا يعرف** من أين تُعرف دولة المستخدم، ويطلبها من مصدر يُحقن —
   القاعدة نفسها التي يقوم عليها `AP_PHONE_FLAG_SOURCE`، وللسبب نفسه: مكتبة
   الواجهة لا تعتمد على خدمة من خدمات التطبيق، وإلّا صار المكوّن غير قابل
   للعرض في موقع التوثيق ولا للاستعمال خارج هذا التطبيق.

   ─── الافتراضي: لا كشف ────────────────────────────────────────────────────
   يعود `null` فيبقى المكوّن على `defaultCountry` أو على السعودية. والتطبيق
   يحقن تنفيذًا يلفّ `IpApiService` القائم أصلًا — انظر `app.module.ts`.

   ⚠️ الكشف **غير متزامن**، والمكوّن يُرسم قبل وصوله. فالتبديل مشروط بأن يكون
      الحقل ما زال فارغًا ولم يُلمَس: تبديل دولة تحت مستخدم بدأ الكتابة يغيّر
      رقمه بلا أن يطلب.
   ============================================================================ */

/** يعيد رمز الدولة أو `null` حين يتعذّر. لا يرمي أبدًا — الفشل يعني «لا أعرف». */
export type ApPhoneCountryDetector = () => Promise<CountryCode | null>;

export const AP_PHONE_COUNTRY_DETECTOR = new InjectionToken<ApPhoneCountryDetector>(
  'AP_PHONE_COUNTRY_DETECTOR',
  { providedIn: 'root', factory: () => () => Promise.resolve(null) },
);
