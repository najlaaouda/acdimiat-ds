import { Directive } from '@angular/core';

/* ============================================================================
   Acadimiat UI — عنوان المجموعة داخل اللوحة المنسدلة
   ----------------------------------------------------------------------------
   موجّه بلا سلوك، مثل `[apMenuOption]`: وجوده كلّه أن أنماط
   `ui/select/_menu.scss` تعيش في ورقة `<ap-menu>`، ولا تصل إلى محتوًى مُسقَط
   إلّا بمحدّد يسمّيه.

   ─── لماذا عنصر يكتبه المستهلك لا مدخل نصّي على اللوحة ─────────────────────
   لوحة تأخذ `[groupLabel]` تصلح لمجموعة واحدة فقط، ثم تُعاد كتابتها عند أوّل
   لوحة بمجموعتين. والمستهلك هنا يكتب البنية كاملةً — عنوانًا ثم
   `role="group"` يلفّ خياراته — فتتّسع اللوحة لأي عدد بلا مدخل جديد.

   ⚠️ ولا `role` هنا: العنوان **ليس** خيارًا ولا عنصر قائمة. الاسم يصل إلى
      قارئ الشاشة عبر `aria-label` على حاوي `role="group"`، ويُخفى العنصر
      المرئي بـ `aria-hidden="true"` كي لا يُنطق الاسم مرّتين — يكتبهما
      المستهلك، انظر شريط اللوحة.

   ⚠️ ولا يُوضع خارج `<ap-menu>`: المحدّد يعيش في ورقتها، فالسمة وحدها لا
      ترسم شيئًا في أي مكان آخر — قاعدة الحاوي نفسها في `[apAppHeaderAccount]`.
   ============================================================================ */

@Directive({
  selector: '[apMenuGroupLabel]',
  standalone: true,
})
export class ApMenuGroupLabelDirective {}
