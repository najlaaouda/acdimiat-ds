/** أساس 1024 لا 1000: هو ما يعرضه نظام التشغيل، فيتطابق ما نقوله مع ما يراه. */
const STEP = 1024;
const UNITS = ['B', 'KB', 'MB', 'GB'] as const;

/**
 * `1536` ⇐ `1.5 KB` · `204800` ⇐ `200 KB` · `0` ⇐ `0 B`
 *
 * المنزلة العشرية تظهر تحت 10 فقط: «1.5 MB» معلومة، و«204.8 KB» ضجيج —
 * المستخدم يقارن رتبةً لا يعدّ أعشارًا.
 */
export function formatFileSize(bytes: number | null | undefined): string {
  if (bytes == null || !Number.isFinite(bytes) || bytes < 0) {
    return '';
  }

  let value = bytes;
  let unit = 0;

  while (value >= STEP && unit < UNITS.length - 1) {
    value /= STEP;
    unit += 1;
  }

  /* البايت لا كسر له، وما تحت 10 يأخذ منزلة واحدة إن كان لها معنى. */
  const rounded = unit === 0 || value >= 10 ? Math.round(value) : Math.round(value * 10) / 10;

  return `${rounded} ${UNITS[unit]}`;
}
