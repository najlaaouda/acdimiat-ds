import { ElementRef, inject } from '@angular/core';

/* ============================================================================
   Acadimiat UI — عقد عنصر التحكّم داخل الحقل
   ----------------------------------------------------------------------------
   `<ap-field>` لا يعرف نوع ما يُسقَط فيه. يعرف فقط أنه شيء يقبل الربط:
   معرّفًا، ووصفًا، وإعلان إلزام، وحالة بطلان.

   ─── لماذا صنف مجرّد لا واجهة ──────────────────────────────────────────────
   الواجهة (`interface`) تختفي عند الترجمة، فلا تصلح رمز حقن. والصنف المجرّد
   رمز حقيقي وقت التشغيل، فيصلح للأمرين معًا: عقدًا للأنواع، ورمزًا لـ
   `@ContentChild` و`useExisting`.

   ─── لماذا التنفيذ هنا لا في كل موجّه ─────────────────────────────────────
   منطق الربط واحد حرفيًا لكل عنصر تحكّم في النظام: الحقل النصّي، والقائمة
   المنسدلة، ومربّع الاختيار، والراديو، والمفتاح. تكراره في خمسة موجّهات يعني
   أن إصلاح خلل في أحدها لا يصل إلى البقية — وهذا بالضبط ما أنتج 1256 حقلًا
   بلا `id` في المشروع: انضباط مكرَّر في مواضع كثيرة.

   عناصر الاختيار الثلاثة ترث من `ApChoiceControl` الذي يرث من هذا الصنف،
   فتأخذ الربط كما هو وتضيف إليه الشكل المرسوم وحده.

   ⚠️ الوريث لا يعلن مُنشئًا: كل الحقن هنا عبر `inject()` في مُهيّئ حقل،
      وهو يعمل داخل سياق حقن الوريث. إعلان مُنشئ في الصنف المجرّد كان
      سيُلزم كل وريث بتمرير تبعياته يدويًا.
   ============================================================================ */

export abstract class ApFieldControl {
  /** العنصر الأصلي — `<input>` أو `<textarea>` أو `<select>`. */
  readonly element = inject<ElementRef<HTMLElement>>(ElementRef);

  /**
   * هل يرسم الحقل الحاوي سهمًا في طرفه؟
   *
   * القائمة المنسدلة وحدها. السهم يعيش في قالب `<ap-field>` لا في صورة
   * خلفية على العنصر: الصورة كانت ستُدفن فيها قيمة لون خام غير قابلة
   * للاشتقاق من token، والسهم عندها لا يتبع لون النصّ ولا الحالة المعطَّلة.
   */
  readonly indicator: 'none' | 'chevron' = 'none';

  /**
   * هل يطلب عنصر التحكّم معاملة الصفّ الملاصق ولو بلا لاصقة مُسقَطة؟
   *
   * معاملة الصفّ (`.ap-field__control[data-affixed]`) تنقل الحدّ والتعبئة
   * وحلقة التركيز من العنصر إلى الصفّ كلّه، فيُقرأ صندوقًا واحدًا. وهي ما
   * يحتاجه أي عنصر **مركّب**: حقل الهاتف عنصرا تحكّم داخل حدّ واحد، وكذلك
   * نطاق التاريخ ومبلغٌ بعملة قابلة للتغيير.
   *
   * ⚠️ يُعلَن هنا لا يُستنتَج من وجود لاصقة: المكوّن المركّب لا يُسقِط
   *    `apFieldPrefix` — تلك موجّهة نصّ ساكن `aria-hidden`، ووضع زرّ يفتح
   *    قائمة داخلها نقيضها الدلالي.
   */
  readonly affixed: boolean = false;

  /**
   * هل يُقرأ صفّ الحقل كلّه من اليسار؟
   *
   * يلزم حين توجد لاصقة مع محتوى لاتيني — انظر `ap-field-kind.ts`.
   */
  ltrRow(): boolean {
    return false;
  }

  /** ربط الهوية والوصف والإلزام — يستدعيه الحقل الحاوي وحده. */
  wire(id: string, describedBy: string | null, required: boolean): void {
    const el = this.element.nativeElement;

    if (!el.id) {
      el.id = id;
    }

    if (describedBy) {
      el.setAttribute('aria-describedby', describedBy);
    } else {
      el.removeAttribute('aria-describedby');
    }

    /*
      `aria-required` لا سمة `required` وحدها: الأخيرة تُفعّل تحقّق المتصفّح
      الأصلي برسائله الإنجليزية غير القابلة للتنسيق، وهو ما لا نريده مع
      واجهة عربية لها رسائلها الخاصة.
    */
    if (required) {
      el.setAttribute('aria-required', 'true');
    } else {
      el.removeAttribute('aria-required');
    }
  }

  /**
   * يمرّر معرّف الـ label — يستدعيه الحقل الحاوي.
   *
   * لا يحتاجه إلا المكوّن **المركّب**: عنصر تحكّم واحد يكفيه `for`/`id`، أمّا
   * حقل يضمّ زرًّا وحقلًا فيحتاج `aria-labelledby` على مجموعته كي يعرف
   * الواصل إلى الزرّ أنه داخل «رقم الجوال» لا معلّقًا في الفراغ.
   *
   * افتراضه لا شيء، فلا يتأثّر أي عنصر تحكّم قائم.
   */
  setLabelId(_id: string): void {}

  setAriaInvalid(invalid: boolean): void {
    const el = this.element.nativeElement;
    if (invalid) {
      el.setAttribute('aria-invalid', 'true');
    } else {
      el.removeAttribute('aria-invalid');
    }
  }

  /** يعكس حالة البطلان على أنماط العنصر نفسه. */
  abstract setInvalid(value: boolean): void;
}
