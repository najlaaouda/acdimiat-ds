import { DocSection } from './doc.model';

/* ============================================================================
   Acadimiat Design System Docs — مراسي الأقسام (Anchors)
   ----------------------------------------------------------------------------
   ⛔ هذا الملف هو المصدر الوحيد لتوليد مُعرِّف القسم.
      الفهرس يبني الروابط منه، والمُصيّر يضع `id` منه. لو حسب كلٌّ منهما
      المُعرِّف بطريقته لانحرفا بصمت، ولوجد المستخدم فهرسًا بروابط ميّتة —
      وهو عطل لا يظهر في أي بناء ولا اختبار نوع.

   لماذا الفهرسة بالموضع لا بنصّ العنوان:
   العناوين عربية، وتحويلها إلى slug لاتيني يفقد المعنى، وتركها عربية في
   الـ URL يُنتج ترميزًا مشوّهًا عند النسخ (`%D8%A7%D9%84...`). والأهمّ:
   عنوانان متطابقان في صفحة واحدة (وارد جدًا — «الحالات» في أكثر من سياق)
   يُنتجان مرساة مكرّرة، فيقفز المتصفّح دائمًا إلى الأولى.

   الموضع فريد دائمًا، ومستقرّ ما دام ترتيب الأقسام مستقرًّا. وإعادة ترتيب
   الأقسام تغيّر الروابط المحفوظة — وهي كلفة مقبولة مقابل مرساة لا تنكسر.
   ============================================================================ */

/** المُعرِّف المستخدم في `id` وفي `href="#…"` على السواء. */
export function docSectionAnchor(index: number): string {
  return `docs-section-${index}`;
}

/** العنوان المعروض في الفهرس، أو `null` لقسم بلا عنوان (لا يُفهرس). */
export function docSectionTitle(section: DocSection): string | null {
  switch (section.kind) {
    case 'prose':
    case 'list':
    case 'table':
    case 'anatomy':
    case 'tokens':
    case 'demo':
    case 'matrix':
    case 'do-dont':
      return section.title ?? null;

    /*
      صندوق التنبيه لا يُفهرس ولو حمل عنوانًا: هو تعليق على ما حوله لا قسم
      قائم بذاته، وإدراجه يضخّم الفهرس بمداخل لا يقصد أحد القفز إليها.
    */
    case 'callout':
      return null;
  }
}
