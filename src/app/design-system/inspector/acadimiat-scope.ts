/* =============================================================================
   طبقة المواءمة بين فاحص النظام ونطاق توكنات أكاديميات.
   -----------------------------------------------------------------------------
   الأداة كُتبت لنظام تصريحه كلّه على `:root`. نظامنا ليس كذلك: الطبقة الأوّلية
   وحدها على `:root` (170 توكنًا)، بينما الطبقتان الدلالية والمكوّنات مقصورتان
   على `.ap-admin, .ap-docs` (722 توكنًا) — عمدًا، حتى لا تتسرّب هوية اللوحة
   البنفسجية إلى موقع الأكاديمية العام الأخضر.

   بلا هذا الملفّ تفشل الأداة في ثلاثة مواضع، وكلّها تفشل **بصمت**:

     1. الاكتشاف — `selectorIsRoot()` يرفض كل قاعدة محدّدها `.ap-docs`،
        فلا تظهر 722 توكنًا في القوائم أصلًا.

     2. القراءة — `getComputedStyle(documentElement)` يعيد نصًّا فارغًا لكل
        توكن مقصور. لا خطأ، لا تحذير: قيمة فارغة تُقرأ كتوكن غير معرَّف.
        (الفخّ نفسه الموثَّق لـ`DocTokensComponent` في CLAUDE.md.)

     3. الكتابة — التصريح **على** العنصر يهزم أي قيمة موروثة من `<html>` مهما
        بلغت خصوصيتها. فقاعدة `:root:root{…}` التي تحقنها الأداة تُشتَقّ صحيحة
        وتُطبَّق على `<html>` ولا تصل `.ap-docs` أبدًا: تُسحَب مقابض منتقي
        اللون ولا يتغيّر شيء على الشاشة.

   ⚠️ هذا هو الحدّ الفاصل: كل تعديل على مصدر الأداة يشير إلى هنا بعلامة
      `[تعديل أكاديميات]`، ولا يوجد تعديل آخر. عند سحب تحديث من الأصل، هذه
      العلامات وحدها هي ما يُراجَع.
   ============================================================================ */

/** النطاقان اللذان تُصرَّح عندهما الطبقتان الدلالية والمكوّنات. */
const AP_SCOPES = ['.ap-docs', '.ap-admin'] as const;

/**
 * هل يصرّح هذا المحدّد توكنات النظام؟
 *
 * يُطابَق بالاحتواء لا بالمساواة، لأن الطبقتين تُكتبان بمحدّد مركّب
 * (`.ap-admin, .ap-docs`) وقد يسبقهما أو يلحقهما شيء.
 */
export function isApTokenScope(selector: string): boolean {
  return AP_SCOPES.some((s) => selector.includes(s));
}

/**
 * العنصر الذي تُقرأ منه القيم المحسوبة.
 *
 * ⚠️ لا تُبدّله بـ`documentElement`. الطبقتان مقصورتان، والجذر يعيد نصًّا
 *    فارغًا لكل توكن فيهما — وهو فشل صامت يبدو كتوكنات غير معرَّفة.
 *
 * السقوط إلى `documentElement` عند غياب النطاق مقصود: الطبقة الأوّلية معرَّفة
 * هناك فعلًا، فتبقى 170 توكنًا مقروءة بدل صفر.
 */
export function apComputedScope(): Element {
  for (const s of AP_SCOPES) {
    const el = document.querySelector(s);
    if (el) return el;
  }
  return document.documentElement;
}

/**
 * قاعدة CSS تُطبّق التصريحات داخل نطاق النظام.
 *
 * المحدّد مضاعَف (`.ap-docs.ap-docs`) ليبلغ خصوصية (0,2,0) ويتجاوز طبقة
 * التوكنات نفسها (0,1,0) بلا `!important`. القاعدة تُضاف **بجانب** قاعدة
 * `:root` التي تولّدها الأداة لا بدلًا منها: الأولى تخدم التوكنات المقصورة،
 * والثانية تخدم الطبقة الأوّلية ومن يرثها خارج النطاق.
 */
export function apScopedRule(declarations: string): string {
  if (!declarations) return '';
  return `.ap-docs.ap-docs,.ap-admin.ap-admin{${declarations}}`;
}

/* ── التصنيف ──────────────────────────────────────────────────────────────
   جداول الأداة الأصلية مبنيّة على نظام آخر (Orange · Ink · Coupon)، فسلالمنا
   كلّها كانت تسقط في «Other» — قائمة واحدة بمئات الأسماء بلا ترتيب.

   الطبقة الثالثة لا تُصنَّف بجدول: 632 توكنًا موزّعة على عشرات المكوّنات،
   وأي قائمة مكتوبة يدويًّا تتقادم عند إضافة المكوّن التالي. تُشتقّ المجموعة من
   الاسم نفسه (`--ap-table-header-bg` ← «table»)، فالمكوّن الجديد يُصنَّف يوم
   كتابته بلا تعديل هنا.
   ------------------------------------------------------------------------ */

type ApKind = 'primitive' | 'semantic';

/** سلالم الطبقة الأوّلية — `:root`، مقاييس خام بلا معنى. */
const AP_PRIMITIVES: ReadonlyArray<readonly [RegExp, string]> = [
  [/^ap-purple-/, 'بنفسجي'],
  [/^ap-slate-/, 'رمادي'],
  [/^ap-blue-/, 'أزرق'],
  [/^ap-teal-/, 'فيروزي'],
  [/^ap-amber-/, 'كهرماني'],
  [/^ap-red-/, 'أحمر'],
  [/^ap-magenta-/, 'أرجواني'],
];

/** أدوار الطبقة الدلالية — الترتيب هو ترتيب العرض. */
const AP_SEMANTICS: ReadonlyArray<readonly [RegExp, string]> = [
  [/^ap-color-bg-/, 'الأسطح'],
  [/^ap-color-text-/, 'النصوص'],
  [/^ap-color-border-/, 'الحدود'],
  [/^ap-color-action-/, 'الأفعال'],
  [/^ap-color-(success|error|warning|info|danger)/, 'الحالات'],
  [/^ap-color-focus-/, 'التركيز'],
];

/**
 * يُصنِّف اسمًا وفق طبقات أكاديميات، أو `null` لما لا يخصّها.
 *
 * إعادة `null` — لا مجموعة «غير مصنَّف» — مقصودة: التصنيف الأصلي يبقى
 * المسؤول عمّا ليس `--ap-*`، فلا تبتلع هذه الدالّة توكنات ليست لنا.
 */
export function apClassify(name: string): { kind: ApKind; group: string } | null {
  for (const [test, group] of AP_PRIMITIVES) {
    if (test.test(name)) return { kind: 'primitive', group };
  }
  for (const [test, group] of AP_SEMANTICS) {
    if (test.test(name)) return { kind: 'semantic', group };
  }

  /*
    الطبقة الثالثة: `--ap-<مكوّن>-<خاصّية>`. الشرط `\w-\w` يمنع التقاط
    `--ap-space-4` ونظائرها من الطبقة الأوّلية، فهي مقاييس لا مكوّنات.
  */
  const component = /^ap-([a-z]+(?:-[a-z]+)*?)-(?:bg|fg|border|color|text|icon|shadow|ring|fill)/.exec(
    name,
  );
  if (component) return { kind: 'semantic', group: component[1] };

  return null;
}
